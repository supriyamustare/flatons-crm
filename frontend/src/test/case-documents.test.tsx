import { screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, describe, expect, it, vi } from "vitest";
import type { CaseDoc, Folder } from "../hooks/useCaseDocs";
import type { CaseDetail } from "../hooks/usePostSales";
import { makeUser, mockApi } from "./mockApi";
import { renderApp } from "./render";

beforeEach(() => vi.restoreAllMocks());

const kase = {
  id: 4, case_code: "PSC-00004", status: "accepted", onboarding_status: "documents_pending", customer: "Anita Desai", project: "Habitat", unit_no: "1114",
  booking_id: 9, booking_code: "BKG-00009", booking_date: "2026-11-17", agreed_price: 3_225_000, owner: null, sales_exec: null, created_at: "2026-11-17T05:00:00Z",
  kyc_done: 0, kyc_total: 4, returned_reason: null, clarification_reason: null, accepted_at: "2026-11-17T05:00:00Z", handover: [], profile: null, co_applicants: [],
  requirements: [], documents: [], profile_problems: [], can_edit: false, can_view_kyc: false, history: [],
} as unknown as CaseDetail;
const cats = ["01 Booking & Application", "02 KYC & Customer Details", "03 Agreements & Legal", "04 Demands & Invoices", "05 Payments & Receipts"]
  .map((label, i) => ({ key: ["booking", "kyc", "agreements", "demands", "payments"][i], label, count: i === 2 ? 1 : i === 4 ? 2 : 0, can_upload: true }));
const doc: CaseDoc = {
  id: 11, doc_no: "DOC-00011", category: "agreements", doc_type: "Sale agreement draft", title: "Draft agreement", doc_number: "AGR-001", doc_date: "2026-11-18",
  expiry_date: null, linked_ref: "BKG-00009", file_name: "draft.pdf", file_type: "application/pdf", file_size: 245_000, sha256: "a".repeat(64), verification: "pending",
  approval: "under_approval", visibility: "internal", status_reason: null, version: 1, supersedes: null, superseded: false, version_reason: null,
  uploaded_by: { id: 1, full_name: "Leela Legal", role: "legal" }, uploaded_at: "2026-11-18T05:00:00Z", reviewed_by: null, reviewed_at: null, released_at: null,
  url: "/api/post-sales/documents/11/file", can_review: false, can_release: false, can_withdraw: false, can_replace: true,
};
const folder: Folder = { categories: cats, documents: [doc], system: [
  { category: "payments", title: "Receipt Rs 3,22,500", kind: "Receipt", number: "RCT-00001", date: "2026-11-17", status: "confirmed", url: "/statement/4" },
  { category: "payments", title: "Statement of account (always current)", kind: "Statement", number: null, date: null, status: "live", url: "/statement/4" }] };

async function openDocs() {
  await userEvent.click(await screen.findByRole("tab", { name: "Documents" }));
  return screen.findByRole("tabpanel", { name: "Documents" });
}

describe("customer folder", () => {
  it("shows the folders with counts, and generated documents in their folder", async () => {
    mockApi(makeUser("postsales_exec"), { get: { "/post-sales/cases/4": kase, "/post-sales/cases/4/documents": folder } });
    renderApp("/post-sales/4");
    const panel = await openDocs();
    const nav = within(panel).getByRole("navigation", { name: "Folders" });
    expect(within(nav).getByRole("button", { name: /03 Agreements & Legal\s*1/ })).toBeInTheDocument();
    await userEvent.click(within(nav).getByRole("button", { name: /05 Payments & Receipts/ }));
    const gen = within(panel).getByRole("list", { name: "Generated by the CRM" });
    expect(gen).toHaveTextContent("RCT-00001"); expect(gen).toHaveTextContent("Statement of account");
  });

  it("the uploader sees it waiting for someone else; details and fingerprint are shown", async () => {
    mockApi(makeUser("legal", { id: 1 }), { get: { "/post-sales/cases/4": kase, "/post-sales/cases/4/documents": folder } });
    renderApp("/post-sales/4");
    const panel = await openDocs();
    await userEvent.click(within(panel).getByRole("button", { name: /03 Agreements & Legal/ }));
    expect(panel).toHaveTextContent("Waiting for a reviewer (not the uploader)");
    expect(panel).toHaveTextContent("Number: AGR-001"); expect(panel).toHaveTextContent("Fingerprint: aaaaaaaaaaaa…");
    expect(within(panel).queryByRole("button", { name: "Approve" })).not.toBeInTheDocument();
  });

  it("uploading needs a type, title and file", async () => {
    const { post } = mockApi(makeUser("legal"), { get: { "/post-sales/cases/4": kase, "/post-sales/cases/4/documents": folder }, post: { "/post-sales/cases/4/documents": folder } });
    renderApp("/post-sales/4");
    const panel = await openDocs();
    await userEvent.click(within(panel).getByRole("button", { name: /03 Agreements & Legal/ }));
    await userEvent.click(within(panel).getByRole("button", { name: "Upload" }));
    const d = await screen.findByRole("dialog", { name: "Upload to 03 Agreements & Legal" });
    expect(within(d).getByRole("button", { name: "Upload" })).toBeDisabled();
    await userEvent.type(within(d).getByLabelText("Document type"), "Allotment letter");
    await userEvent.type(within(d).getByLabelText("Title"), "Allotment letter, unit 1114");
    await userEvent.upload(within(d).getByLabelText("File"), new File([new Uint8Array([0x25, 0x50, 0x44, 0x46])], "allot.pdf", { type: "application/pdf" }));
    await userEvent.click(within(d).getByRole("button", { name: "Upload" }));
    await waitFor(() => expect(post).toHaveBeenCalled());
    const form = post.mock.calls[0][1] as FormData;
    expect([form.get("category"), form.get("doc_type"), (form.get("file") as File).name]).toEqual(["agreements", "Allotment letter", "allot.pdf"]);
    expect(await screen.findByText("Document uploaded for review")).toBeInTheDocument();
  });

  it("a new version needs a reason", async () => {
    const { post } = mockApi(makeUser("legal"), { get: { "/post-sales/cases/4": kase, "/post-sales/cases/4/documents": folder }, post: { "/post-sales/cases/4/documents": folder } });
    renderApp("/post-sales/4");
    const panel = await openDocs();
    await userEvent.click(within(panel).getByRole("button", { name: /03 Agreements & Legal/ }));
    await userEvent.click(within(panel).getByRole("button", { name: "New version" }));
    const d = await screen.findByRole("dialog", { name: "New version: Draft agreement" });
    await userEvent.upload(within(d).getByLabelText("File"), new File([new Uint8Array([0x25, 0x50])], "v2.pdf", { type: "application/pdf" }));
    expect(within(d).getByRole("button", { name: "Upload" })).toBeDisabled();
    await userEvent.type(within(d).getByLabelText("Reason for the new version"), "Clause 7 corrected");
    await userEvent.click(within(d).getByRole("button", { name: "Upload" }));
    await waitFor(() => expect(post).toHaveBeenCalled());
    const form = post.mock.calls[0][1] as FormData;
    expect([form.get("replaces_id"), form.get("version_reason"), form.get("doc_number")]).toEqual(["11", "Clause 7 corrected", "AGR-001"]);
  });

  it("a CRM manager releases an approved document; withdrawing asks for a reason", async () => {
    const approved = { ...doc, approval: "approved" as const, verification: "verified" as const, can_release: true, can_withdraw: true };
    const released = { ...approved, approval: "released" as const, visibility: "customer" as const, can_release: false };
    const { post } = mockApi(makeUser("crm_manager"), { get: { "/post-sales/cases/4": kase, "/post-sales/cases/4/documents": { ...folder, documents: [approved] } },
      post: { "/post-sales/documents/11/release": { ...folder, documents: [released] }, "/post-sales/documents/11/withdraw": { ...folder, documents: [{ ...released, approval: "withdrawn", visibility: "internal", status_reason: "Wrong unit" }] } } });
    renderApp("/post-sales/4");
    const panel = await openDocs();
    await userEvent.click(within(panel).getByRole("button", { name: /03 Agreements & Legal/ }));
    await userEvent.click(within(panel).getByRole("button", { name: "Release to customer" }));
    expect(await within(panel).findByText("Customer can see")).toBeInTheDocument();
    await userEvent.click(within(panel).getByRole("button", { name: "Withdraw" }));
    const d = await screen.findByRole("dialog", { name: "Withdraw Draft agreement" });
    expect(d).toHaveTextContent("The customer will no longer see this document");
    await userEvent.type(within(d).getByLabelText("Reason"), "Wrong unit");
    await userEvent.click(within(d).getByRole("button", { name: "Withdraw" }));
    await waitFor(() => expect(post).toHaveBeenCalledWith("/post-sales/documents/11/withdraw", { reason: "Wrong unit" }));
  });
});
